// Bundles sanitize-html and its dependencies into one ES module at src/vendor/sanitize-html.js.
//
// Why: sanitize-html is CommonJS and require()s htmlparser2, which is ESM-only since v11. Vercel's
// function runtime replaces Node's module loader and rejects require() of ES modules on every Node
// version (ERR_REQUIRE_ESM), so the API crashed on load. Bundling removes that runtime require().
// Re-run after upgrading sanitize-html:  npm run vendor:sanitize-html
import { build } from 'esbuild';

await build({
  entryPoints: ['node_modules/sanitize-html/index.js'],
  outfile: 'src/vendor/sanitize-html.js',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  legalComments: 'eof',
  banner: {
    js: [
      "// GENERATED by scripts/vendor-sanitize-html.js (npm run vendor:sanitize-html). Do not edit.",
      "import { createRequire } from 'node:module';",
      'const require = createRequire(import.meta.url);',
    ].join('\n'),
  },
});
